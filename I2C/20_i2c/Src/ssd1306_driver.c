void OLED_WriteChar(uint8_t slave_addr,uint8_t data_mem_addr_ssd1306,char x)
{

	/*1.Find the index of the Font5x8 for current character... */
	uint8_t index = x - 32;

	/*2.Get copy the 5 bytes of pixel data into the temp buffer to transfer... */
	uint8_t temp_buffer[6];

	for(int i=0; i<5; i++)
	{
		temp_buffer[i] = Font5x8[index][i];

	}

	/*Set 0x00 for last byte inorder prevent character joining... */
	temp_buffer[5] = 0x00;

	i2c_Burst_Write(slave_addr,data_mem_addr_ssd1306,(char *)temp_buffer,sizeof(temp_buffer));

}

void OLED_WriteString(uint8_t slave_addr,uint8_t data_mem_addr_ssd1306,char *str)
{
	while(*str)
	{
		/*Pass the Every character in the string o the OLED_WriteChar function... */
		OLED_WriteChar(slave_addr,data_mem_addr_ssd1306,*str);

		str++;
	}
}

void Set_Cursor(uint8_t slave_addr,uint8_t cmd_mem_addr_ssd1306,uint8_t page_addr,uint8_t col_start_addr)
{

	uint8_t cmnds[3];

	/*1.Set the page address... */
	page_addr &= (0x0F);
	cmnds[0] = ((page_addr) | 0xB0);						//page address

	/*2.Set the Lower nibble Start COL address... */
	cmnds[1] = (0x00 | (col_start_addr & 0x0F));			//lower nibble

	/*3.Set the Higher nibble Start COL address... */
	cmnds[2] = (((col_start_addr & 0xF0) >>4) | 0x10);		//upper nibble

	// Burst all 3 commands at once!
	i2c_Burst_Write(slave_addr,cmd_mem_addr_ssd1306,(char *)cmnds,sizeof(cmnds));


}
